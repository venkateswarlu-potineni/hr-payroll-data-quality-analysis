
CREATE TABLE HR_EMPLOYEES_RAW (
    EMPLOYEE_ID             VARCHAR2(30),
    EMPLOYEE_NAME           VARCHAR2(100),
    DEPARTMENT              VARCHAR2(60),
    LOCATION                VARCHAR2(60),
    HIRE_DATE               VARCHAR2(30),
    EMPLOYMENT_STATUS       VARCHAR2(30),
    MONTHLY_BASE_SALARY_INR VARCHAR2(30),
    BANK_ACCOUNT_LAST4      VARCHAR2(10)
);




SELECT *
FROM HR_EMPLOYEES_RAW;





CREATE TABLE HR_PAYROLL_RAW (
    PAYROLL_ID           VARCHAR2(30),
    EMPLOYEE_ID          VARCHAR2(30),
    PAYROLL_MONTH        VARCHAR2(20),
    BASE_PAY_INR         VARCHAR2(30),
    ALLOWANCE_INR        VARCHAR2(30),
    DEDUCTION_INR        VARCHAR2(30),
    RECORDED_NET_PAY_INR VARCHAR2(30)
);





SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'HR_EMPLOYEES_RAW',
    'HR_PAYROLL_RAW'
)
ORDER BY TABLE_NAME;





SELECT COUNT(*) AS TOTAL_EMPLOYEES
FROM HR_EMPLOYEES_RAW;




SELECT *
FROM HR_EMPLOYEES_RAW
FETCH FIRST 10 ROWS ONLY;




SELECT COUNT(*) AS TOTAL_PAYROLL_RECORDS
FROM HR_PAYROLL_RAW;



SELECT *
FROM HR_PAYROLL_RAW
FETCH FIRST 10 ROWS ONLY;





SELECT 'EMPLOYEES' AS DATASET,
       COUNT(*) AS TOTAL_RECORDS
FROM HR_EMPLOYEES_RAW

UNION ALL

SELECT 'PAYROLL' AS DATASET,
       COUNT(*) AS TOTAL_RECORDS
FROM HR_PAYROLL_RAW;





SELECT
    EMPLOYEE_ID,
    COUNT(*) AS DUPLICATE_COUNT
FROM HR_EMPLOYEES_RAW
WHERE EMPLOYEE_ID IS NOT NULL
GROUP BY EMPLOYEE_ID
HAVING COUNT(*) > 1
ORDER BY DUPLICATE_COUNT DESC;





SELECT
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    DEPARTMENT,
    LOCATION,
    HIRE_DATE,
    MONTHLY_BASE_SALARY_INR
FROM HR_EMPLOYEES_RAW
WHERE EMPLOYEE_ID IS NULL
   OR TRIM(EMPLOYEE_NAME) IS NULL
   OR TRIM(DEPARTMENT) IS NULL
   OR TRIM(LOCATION) IS NULL
   OR TRIM(HIRE_DATE) IS NULL
   OR TRIM(MONTHLY_BASE_SALARY_INR) IS NULL;






SELECT
    EMPLOYEE_ID,
    EMPLOYEE_NAME,
    MONTHLY_BASE_SALARY_INR
FROM HR_EMPLOYEES_RAW
WHERE TRIM(MONTHLY_BASE_SALARY_INR) IS NOT NULL
  AND (
      VALIDATE_CONVERSION(
          TRIM(MONTHLY_BASE_SALARY_INR)
          AS NUMBER
      ) = 0
      OR
      TO_NUMBER(
          TRIM(MONTHLY_BASE_SALARY_INR)
          DEFAULT NULL ON CONVERSION ERROR
      ) <= 0
  );





SELECT
    PAYROLL_ID,
    EMPLOYEE_ID,
    BASE_PAY_INR,
    ALLOWANCE_INR,
    DEDUCTION_INR,
    RECORDED_NET_PAY_INR,
    (
        TO_NUMBER(BASE_PAY_INR)
        + TO_NUMBER(ALLOWANCE_INR)
        - TO_NUMBER(DEDUCTION_INR)
    ) AS CALCULATED_NET_PAY,
    (
        TO_NUMBER(RECORDED_NET_PAY_INR)
        - (
            TO_NUMBER(BASE_PAY_INR)
            + TO_NUMBER(ALLOWANCE_INR)
            - TO_NUMBER(DEDUCTION_INR)
        )
    ) AS SALARY_DIFFERENCE
FROM HR_PAYROLL_RAW
WHERE
    VALIDATE_CONVERSION(BASE_PAY_INR AS NUMBER) = 1
    AND VALIDATE_CONVERSION(ALLOWANCE_INR AS NUMBER) = 1
    AND VALIDATE_CONVERSION(DEDUCTION_INR AS NUMBER) = 1
    AND VALIDATE_CONVERSION(RECORDED_NET_PAY_INR AS NUMBER) = 1
    AND (
        TO_NUMBER(RECORDED_NET_PAY_INR)
        - (
            TO_NUMBER(BASE_PAY_INR)
            + TO_NUMBER(ALLOWANCE_INR)
            - TO_NUMBER(DEDUCTION_INR)
        )
    ) <> 0;






SELECT
    P.PAYROLL_ID,
    P.EMPLOYEE_ID,
    P.PAYROLL_MONTH,
    P.RECORDED_NET_PAY_INR
FROM HR_PAYROLL_RAW P
LEFT JOIN HR_EMPLOYEES_RAW E
    ON P.EMPLOYEE_ID = E.EMPLOYEE_ID
WHERE E.EMPLOYEE_ID IS NULL
  AND P.EMPLOYEE_ID IS NOT NULL;






SELECT
    PAYROLL_ID,
    EMPLOYEE_ID,
    PAYROLL_MONTH,
    RECORDED_NET_PAY_INR
FROM HR_PAYROLL_RAW
WHERE TRIM(EMPLOYEE_ID) IS NULL;




SELECT
    'Total Employee Records' AS CHECK_NAME,
    COUNT(*) AS RECORD_COUNT
FROM HR_EMPLOYEES_RAW

UNION ALL

SELECT
    'Total Payroll Records',
    COUNT(*)
FROM HR_PAYROLL_RAW

UNION ALL

SELECT
    'Duplicate Employee IDs',
    COUNT(*)
FROM (
    SELECT EMPLOYEE_ID
    FROM HR_EMPLOYEES_RAW
    WHERE EMPLOYEE_ID IS NOT NULL
    GROUP BY EMPLOYEE_ID
    HAVING COUNT(*) > 1
)

UNION ALL

SELECT
    'Missing Employee Information',
    COUNT(*)
FROM HR_EMPLOYEES_RAW
WHERE EMPLOYEE_ID IS NULL
   OR TRIM(EMPLOYEE_NAME) IS NULL
   OR TRIM(DEPARTMENT) IS NULL
   OR TRIM(LOCATION) IS NULL
   OR TRIM(HIRE_DATE) IS NULL
   OR TRIM(MONTHLY_BASE_SALARY_INR) IS NULL

UNION ALL

SELECT
    'Invalid Employee Salaries',
    COUNT(*)
FROM HR_EMPLOYEES_RAW
WHERE TRIM(MONTHLY_BASE_SALARY_INR) IS NOT NULL
  AND (
    VALIDATE_CONVERSION(
        TRIM(MONTHLY_BASE_SALARY_INR) AS NUMBER
    ) = 0
    OR TO_NUMBER(
        TRIM(MONTHLY_BASE_SALARY_INR)
        DEFAULT NULL ON CONVERSION ERROR
    ) <= 0
  )

UNION ALL

SELECT
    'Payroll Calculation Errors',
    COUNT(*)
FROM HR_PAYROLL_RAW
WHERE VALIDATE_CONVERSION(BASE_PAY_INR AS NUMBER) = 1
  AND VALIDATE_CONVERSION(ALLOWANCE_INR AS NUMBER) = 1
  AND VALIDATE_CONVERSION(DEDUCTION_INR AS NUMBER) = 1
  AND VALIDATE_CONVERSION(RECORDED_NET_PAY_INR AS NUMBER) = 1
  AND (
    TO_NUMBER(RECORDED_NET_PAY_INR DEFAULT NULL ON CONVERSION ERROR)
    - TO_NUMBER(BASE_PAY_INR DEFAULT NULL ON CONVERSION ERROR)
    - TO_NUMBER(ALLOWANCE_INR DEFAULT NULL ON CONVERSION ERROR)
    + TO_NUMBER(DEDUCTION_INR DEFAULT NULL ON CONVERSION ERROR)
  ) <> 0

UNION ALL

SELECT
    'Unmatched Payroll Employee IDs',
    COUNT(*)
FROM HR_PAYROLL_RAW P
LEFT JOIN HR_EMPLOYEES_RAW E
    ON P.EMPLOYEE_ID = E.EMPLOYEE_ID
WHERE E.EMPLOYEE_ID IS NULL
  AND P.EMPLOYEE_ID IS NOT NULL

UNION ALL

SELECT
    'Missing Payroll Employee IDs',
    COUNT(*)
FROM HR_PAYROLL_RAW
WHERE TRIM(EMPLOYEE_ID) IS NULL;






